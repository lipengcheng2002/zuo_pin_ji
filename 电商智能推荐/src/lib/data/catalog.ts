let paletteIndex = 0;
const nextPalette = (): [string, string, string] => {
  const p = PALETTES[paletteIndex % PALETTES.length];
  paletteIndex += 1;
  return p;
};

type Seed = Omit<Product, "currency" | "editorial"> & {
  editorial: Omit<Product["editorial"], "palette" | "accent">;
};

const mk = (seed: Seed): Product => {
  const [paletteA, paletteB, accent] = nextPalette();
  return {
    currency: "CNY",
    ...seed,
    editorial: { ...seed.editorial, palette: [paletteA, paletteB], accent },
  };
};

