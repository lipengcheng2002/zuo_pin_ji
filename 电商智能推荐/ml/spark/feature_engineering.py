"""Spark feature engineering for the ZHIYAN recommendation system.

Inputs are the canonical interaction and product tables exported from the
transactional store (or generated by ``scripts/simulate_pipeline.py``):

    interactions.csv : user_id, item_id, event_type, ts, session_id
    products.csv     : item_id, category, role, price, rating, stock, tags

Outputs (Parquet + JSON) are consumed by the training jobs and the feature
store warm-up:

    out/features/user_features/
    out/features/item_features/
    out/features/item_cooccurrence/
    out/summary.json

Run locally:
    spark-submit --master 'local[*]' spark/feature_engineering.py \
        --interactions data/interactions.csv \
        --products data/products.csv \
        --out artifacts/spark

Event weights follow the online engine: view 1, click 2, wishlist 3.5,
add_to_cart 5, purchase 8, search 1.2, chat 1.5.
"""

from __future__ import annotations

import argparse
import json
import os
from datetime import datetime, timezone

from pyspark.sql import SparkSession, Window
from pyspark.sql import functions as F
from pyspark.sql import types as T

EVENT_WEIGHTS = {
    "view": 1.0,
    "click": 2.0,
    "wishlist": 3.5,
    "add_to_cart": 5.0,
    "purchase": 8.0,
    "search": 1.2,
    "chat": 1.5,
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="ZHIYAN Spark feature engineering")
    parser.add_argument("--interactions", required=True)
    parser.add_argument("--products", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--days", type=int, default=90)
    return parser.parse_args()


def build_session(app_name: str) -> SparkSession:
    return (
        SparkSession.builder.appName(app_name)
        .config("spark.sql.session.timeZone", "Asia/Shanghai")
        .config("spark.sql.shuffle.partitions", os.getenv("SPARK_SHUFFLE_PARTITIONS", "16"))
        .config("spark.sql.adaptive.enabled", "true")
        .config("spark.sql.adaptive.coalescePartitions.enabled", "true")
        .getOrCreate()
    )


def main() -> None:
    args = parse_args()
    spark = build_session("zhiyan-feature-engineering")
    spark.sparkContext.setLogLevel("WARN")

    interactions = (
        spark.read.option("header", True)
        .option("inferSchema", True)
        .csv(args.interactions)
        .withColumn("ts", F.to_timestamp("ts"))
        .withColumn("weight", F.coalesce(F.col("weight"), F.lit(1.0)))
        .filter(F.col("user_id").isNotNull() & F.col("item_id").isNotNull())
    )
    products = (
        spark.read.option("header", True)
        .option("inferSchema", True)
        .csv(args.products)
        .withColumn("tags", F.split(F.col("tags"), r"\|"))
    )

    max_ts = interactions.agg(F.max("ts")).collect()[0][0]
    cutoff = F.date_sub(F.lit(max_ts).cast("date"), args.days)

    weighted = interactions.withColumn(
        "event_weight",
        F.when(F.col("event_type") == "view", F.lit(EVENT_WEIGHTS["view"]))
        .when(F.col("event_type") == "click", F.lit(EVENT_WEIGHTS["click"]))
        .when(F.col("event_type") == "wishlist", F.lit(EVENT_WEIGHTS["wishlist"]))
        .when(F.col("event_type") == "add_to_cart", F.lit(EVENT_WEIGHTS["add_to_cart"]))
        .when(F.col("event_type") == "purchase", F.lit(EVENT_WEIGHTS["purchase"]))
        .when(F.col("event_type") == "search", F.lit(EVENT_WEIGHTS["search"]))
        .when(F.col("event_type") == "chat", F.lit(EVENT_WEIGHTS["chat"]))
        .otherwise(F.lit(1.0)),
    ).join(products.select("item_id", "price"), "item_id", "left")
    recent = weighted.filter(F.col("ts") >= cutoff)

    # ------------------------------------------------------------------ users
    user_agg = recent.groupBy("user_id").agg(
        F.count("*").alias("events_30d"),
        F.sum(F.when(F.col("event_type") == "purchase", 1).otherwise(0)).alias("purchases_30d"),
        F.sum(F.when(F.col("event_type") == "add_to_cart", 1).otherwise(0)).alias("carts_30d"),
        F.sum(F.when(F.col("event_type") == "wishlist", 1).otherwise(0)).alias("wishlists_30d"),
        F.sum(F.when(F.col("event_type") == "purchase", F.col("price")).otherwise(0)).alias("monetary_30d"),
        F.max("ts").alias("last_event_at"),
        F.countDistinct("session_id").alias("sessions_30d"),
    )
    affinity = (
        recent.join(products.select("item_id", "tags", "category"), "item_id")
        .select("user_id", F.explode("tags").alias("tag"), "event_weight")
        .groupBy("user_id", "tag")
        .agg(F.sum("event_weight").alias("affinity"))
    )
    tag_window = Window.partitionBy("user_id").orderBy(F.desc("affinity"))
    top_tags = (
        affinity.withColumn("rank", F.row_number().over(tag_window))
        .filter(F.col("rank") <= 5)
        .groupBy("user_id")
        .agg(F.collect_list("tag").alias("top_style_tags"))
    )
    category_affinity = (
        recent.join(products.select("item_id", "category"), "item_id")
        .groupBy("user_id", "category")
        .agg(F.sum("event_weight").alias("weight"))
    )
    cat_window = Window.partitionBy("user_id").orderBy(F.desc("weight"))
    top_categories = (
        category_affinity.withColumn("rank", F.row_number().over(cat_window))
        .filter(F.col("rank") <= 3)
        .groupBy("user_id")
        .agg(F.collect_list("category").alias("top_categories"))
    )
    user_features = (
        user_agg.join(top_tags, "user_id", "left")
        .join(top_categories, "user_id", "left")
        .withColumn("recency_days", F.datediff(F.lit(max_ts).cast("date"), F.col("last_event_at").cast("date")))
        .withColumn(
            "recency_decay",
            F.exp(-F.col("recency_days") / F.lit(30.0)),
        )
        .withColumn("rfm_monetary", F.round("monetary_30d", 2))
    )

    # ------------------------------------------------------------------ items
    item_agg = recent.groupBy("item_id").agg(
        F.sum(F.when(F.col("event_type").isin("view", "click"), 1).otherwise(0)).alias("impressions"),
        F.sum(F.when(F.col("event_type").isin("click", "add_to_cart", "wishlist"), 1).otherwise(0)).alias("clicks"),
        F.sum(F.when(F.col("event_type") == "add_to_cart", 1).otherwise(0)).alias("carts"),
        F.sum(F.when(F.col("event_type") == "purchase", 1).otherwise(0)).alias("purchases"),
        F.sum(F.when(F.col("event_type") == "wishlist", 1).otherwise(0)).alias("wishlists"),
        F.max("ts").alias("last_event_at"),
    )
    week_cutoff = F.date_sub(F.lit(max_ts).cast("date"), 7)
    recent_7d = (
        weighted.filter(F.col("ts") >= week_cutoff)
        .groupBy("item_id")
        .agg(F.sum("event_weight").alias("trend_7d"))
    )
    item_features = (
        products.select(
            "item_id",
            "category",
            "role",
            "price",
            F.col("rating").cast("double").alias("rating"),
            F.col("stock").cast("int").alias("stock"),
            "tags",
        )
        .join(item_agg, "item_id", "left")
        .join(recent_7d, "item_id", "left")
        .na.fill(
            {
                "impressions": 0,
                "clicks": 0,
                "carts": 0,
                "purchases": 0,
                "wishlists": 0,
                "trend_7d": 0.0,
            }
        )
        .withColumn("ctr", F.round(F.col("clicks") / F.greatest(F.col("impressions") + F.lit(24), F.lit(1)), 4))
        .withColumn("cvr", F.round(F.col("purchases") / F.greatest(F.col("clicks") + F.lit(32), F.lit(1)), 4))
        .withColumn("cart_rate", F.round(F.col("carts") / F.greatest(F.col("clicks") + F.lit(18), F.lit(1)), 4))
        .withColumn(
            "quality_score",
            F.round(
                (F.least(F.greatest((F.col("rating") - F.lit(4.1)) / F.lit(0.9), F.lit(0.0)), F.lit(1.0)) * F.lit(0.62))
                + F.least(F.log1p(F.col("impressions")) / F.log(F.lit(2000.0)), F.lit(1.0)) * F.lit(0.24)
                + F.lit(0.14),
                4,
            ),
        )
        .withColumn(
            "trend_score",
            F.round(
                F.least(F.col("trend_7d") / F.lit(50.0), F.lit(1.0)) * F.lit(0.55)
                + F.least(F.col("rating") / F.lit(5.0), F.lit(1.0)) * F.lit(0.45),
                4,
            ),
        )
        .withColumn("in_stock", F.when(F.col("stock") > 0, 1).otherwise(0))
    )

    # --------------------------------------------------------- item-item (CF)
    # Co-occurrence over sessions, capped to the 20 strongest neighbours per
    # seed item to keep the online lookup table small.
    sessions = recent.select("session_id", "item_id").distinct()
    left = sessions.withColumnRenamed("item_id", "seed")
    right = sessions.withColumnRenamed("item_id", "neighbour")
    pairs = (
        left.join(right, "session_id")
        .filter(F.col("seed") < F.col("neighbour"))
        .groupBy("seed", "neighbour")
        .agg(F.count("*").alias("co_occurrence"))
    )
    neighbour_window = Window.partitionBy("seed").orderBy(F.desc("co_occurrence"))
    cooccurrence = (
        pairs.withColumn("rank", F.row_number().over(neighbour_window))
        .filter(F.col("rank") <= 20)
        .withColumn("score", F.round(F.col("co_occurrence") / F.lit(8.0), 4))
    )

    # ---------------------------------------------------------------- outputs
    os.makedirs(args.out, exist_ok=True)
    user_features.write.mode("overwrite").parquet(os.path.join(args.out, "features", "user_features"))
    item_features.write.mode("overwrite").parquet(os.path.join(args.out, "features", "item_features"))
    cooccurrence.write.mode("overwrite").parquet(os.path.join(args.out, "features", "item_cooccurrence"))

    summary = {
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "windowDays": args.days,
        "users": user_features.count(),
        "items": item_features.count(),
        "interactions": interactions.count(),
        "pairs": cooccurrence.count(),
        "avgEventsPerUser": round(
            user_features.agg(F.avg("events_30d")).collect()[0][0] or 0.0, 2
        ),
        "eventWeights": EVENT_WEIGHTS,
        "output": args.out,
    }
    with open(os.path.join(args.out, "summary.json"), "w", encoding="utf-8") as handle:
        json.dump(summary, handle, ensure_ascii=False, indent=2)
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    spark.stop()


if __name__ == "__main__":
    main()
